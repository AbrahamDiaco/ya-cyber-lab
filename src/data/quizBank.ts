const wrongAnswers = [
  'Se fier uniquement à la validation de l’interface utilisateur.',
  'Désactiver les contrôles de sécurité pour éviter les erreurs.',
  'Masquer la fonctionnalité sans corriger sa cause.'
];

export function getQuizForLesson(title: string): QuizQuestion[] {
  const topicControls = controls[title] ?? controls['Sécurité des API'];
  return prompts.map((q, index) => {
    const correctAnswer = topicControls[index];
    const correct = index % 4;
    const distractors = wrongAnswers.map((answer) => answer);
    const answers = [...distractors];
    answers.splice(correct, 0, correctAnswer);
    return {
      q: `${q} — ${title}`,
      a: answers,
      correct,
      why: `${correctAnswer} Cette pratique répond directement au risque associé à ${title}.`
    };
  });
}
